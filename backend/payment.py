# نظام دفع تجريبي لاشتراك برو لأغراض المشروع الجامعي فقط
# لا يوجد اتصال بأي بوابة دفع خارجية ولا يتم خصم أي مبلغ حقيقي
# يتم التحقق من شكل بيانات البطاقة فقط
# بيانات البطاقة تستخدم للتحقق لحظياً ثم تهمل ولا تحفظ في قاعدة البيانات
# عند نجاح الدفع ينشأ رقم عملية تجريبي يحفظ مع الاشتراك
# مكتبة التعابير النمطية تستخدم لفحص شكل الأرقام والتواريخ
# مكتبة الأسرار تولد قيماً عشوائية آمنة لرقم العملية
import re
import secrets
from datetime import date

# سعر اشتراك برو بالدولار لمدة شهر واحد
PRO_PRICE_USD = 10


# كلاس خطأ خاص بالدفع يحمل رسالة عربية
# نرفعه عند وجود خطأ في بيانات البطاقة
# ويلتقطه ملف المسارات ليعرض الرسالة للحرفي
class PaymentError(Exception):
    """استثناء خاص بأخطاء الدفع يحمل رسالة عربية تظهر للحرفي"""


# تتحقق هذه الدالة من بيانات البطاقة المرسلة من نموذج الدفع
# تستقبل اسم صاحب البطاقة ورقمها وتاريخ انتهائها ورمز الأمان
# لا تعيد شيئاً إذا كانت البيانات صحيحة
# وترفع خطأ الدفع برسالة واضحة عند أول خطأ تجده
def validate_card(cardholder_name, card_number, expiry, cvv):
    # تنظيف المدخلات قبل فحصها
    # القيمة الفارغة تتحول إلى نص فارغ لتجنب الأخطاء
    # نحذف المسافات الزائدة من الاسم
    # ونحذف المسافات والشرطات من رقم البطاقة
    name = ' '.join(str(cardholder_name or '').split())
    number = re.sub(r'[\s-]', '', str(card_number or ''))
    expiry = str(expiry or '').strip()
    cvv = str(cvv or '').strip()

    # الفحص الأول جميع الحقول مطلوبة
    if not name or not number or not expiry or not cvv:
        raise PaymentError('يرجى تعبئة جميع بيانات البطاقة.')
    # الفحص الثاني الاسم ثلاثة أحرف على الأقل ولا يحتوي أرقاماً
    if len(name) < 3 or re.search(r'\d', name):
        raise PaymentError('اسم صاحب البطاقة غير صحيح.')
    # الفحص الثالث رقم البطاقة يتكون من 16 رقماً بالضبط
    if not re.fullmatch(r'\d{16}', number):
        raise PaymentError('رقم البطاقة يجب أن يتكون من 16 رقماً.')

    # الفحص الرابع تاريخ الانتهاء رقمان للشهر ثم خط مائل ثم رقمان للسنة
    # يجب أن يكون الشهر بين 1 و 12
    match = re.fullmatch(r'(\d{2})\s*/\s*(\d{2})', expiry)
    if not match or not 1 <= int(match.group(1)) <= 12:
        raise PaymentError('تاريخ انتهاء البطاقة يجب أن يكون بالصيغة MM/YY.')
    # نحول السنة من رقمين إلى أربعة أرقام
    # نقارن السنة أولاً ثم الشهر مع الشهر الحالي
    # إذا كان التاريخ أقدم من الشهر الحالي فالبطاقة منتهية
    # ونرفض السنة الأبعد من عشرين سنة لأنها غير منطقية
    month, year = int(match.group(1)), 2000 + int(match.group(2))
    today = date.today()
    if (year, month) < (today.year, today.month):
        raise PaymentError('البطاقة منتهية الصلاحية.')
    if year > today.year + 20:
        raise PaymentError('تاريخ انتهاء البطاقة غير صحيح.')

    # الفحص الخامس رمز الأمان ثلاثة أرقام بالضبط
    if not re.fullmatch(r'\d{3}', cvv):
        raise PaymentError('رمز CVV يجب أن يتكون من 3 أرقام.')


# تنفذ هذه الدالة الدفع التجريبي لاشتراك برو
# تستقبل قاموساً فيه بيانات البطاقة القادمة من الواجهة
# تتحقق من البطاقة أولاً وإذا كانت خاطئة يخرج خطأ الدفع
# عند النجاح تعيد رقم عملية تجريبي يبدأ بالحروف
# SIM
# ثم اثنا عشر حرفاً ورقماً عشوائياً
def charge_pro_subscription(card):
    validate_card(card.get('cardholder_name'), card.get('card_number'), card.get('expiry'), card.get('cvv'))
    return 'SIM-' + secrets.token_hex(6).upper()
